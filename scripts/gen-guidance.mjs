import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const projectRoot = path.resolve(__dirname, '..');
export const mcpSkillsDir = path.join(projectRoot, 'mcp-skills');

export function escapeForTemplateLiteral(str) {
  return str
    .replace(/\\/g, '\\\\')
    .replace(/`/g, '\\`')
    .replace(/\$/g, '\\$');
}

export function generateGuidanceContent() {
  if (!fs.existsSync(mcpSkillsDir)) {
    throw new Error(`Source directory not found: ${mcpSkillsDir}`);
  }

  const files = fs.readdirSync(mcpSkillsDir).filter(f => f.endsWith('.md'));

  let instructionsBody = '';
  const prompts = [];

  for (const file of files) {
    const filepath = path.join(mcpSkillsDir, file);
    const content = fs.readFileSync(filepath, 'utf8');
    
    // Parse frontmatter
    const parts = content.split('---');
    if (parts.length < 3) {
      continue;
    }
    
    const frontmatterRaw = parts[1];
    const body = parts.slice(2).join('---').trim();
    
    const frontmatter = {};
    frontmatterRaw.split('\n').forEach(line => {
      const match = line.match(/^\s*([^:]+)\s*:\s*(.+)\s*$/);
      if (match) {
        frontmatter[match[1].trim()] = match[2].trim();
      }
    });
    
    const name = frontmatter.name || path.basename(file, '.md');
    const description = (frontmatter.description || '').replace(/\\/g, '\\\\').replace(/"/g, '\\"');
    const escapedName = name.replace(/\\/g, '\\\\').replace(/"/g, '\\"');
    const surface = (frontmatter.surface || 'prompt').toLowerCase();
    
    if (surface === 'instructions') {
      instructionsBody = body;
    } else if (surface === 'prompt') {
      prompts.push({
        name: escapedName,
        description,
        body
      });
    }
  }

  return `// AUTO-GENERATED by scripts/gen-guidance.mjs — DO NOT EDIT.

export const SERVER_INSTRUCTIONS = \`${escapeForTemplateLiteral(instructionsBody)}\`;

export interface GuidancePrompt {
  name: string;
  description: string;
  body: string;
}

export const GUIDANCE_PROMPTS: GuidancePrompt[] = [
${prompts.map(p => `  {
    name: "${p.name}",
    description: "${p.description}",
    body: \`${escapeForTemplateLiteral(p.body)}\`
  }`).join(',\n')}
];
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  console.log('▶ Running guidance code generator...');
  try {
    const outputContent = generateGuidanceContent();
    const outputDir = path.join(projectRoot, 'mcp-server', 'src', 'generated');
    const outputFile = path.join(outputDir, 'guidance.ts');
    
    if (!fs.existsSync(outputDir)) {
      fs.mkdirSync(outputDir, { recursive: true });
    }
    
    fs.writeFileSync(outputFile, outputContent, 'utf8');
    console.log(`✅ Successfully generated ${outputFile}`);
  } catch (err) {
    console.error(`❌ Generation failed: ${err.message}`);
    process.exit(1);
  }
}
